#!/usr/bin/env node
/**
 * Builds the on-device alt text web worker into
 * `public/static/local-alt-text/worker.js`.
 *
 * The worker is bundled with esbuild rather than Metro because
 * `@huggingface/transformers` ships ESM only, which Metro cannot bundle. The
 * output is committed, so this only needs to run when the worker source or the
 * transformers dependency changes.
 *
 * esbuild is intentionally not a dependency: it is already present as part of
 * the Expo toolchain, and pinning our own copy just to run this script would
 * mean keeping two versions in sync.
 *
 * Usage: node scripts/build-local-alt-text.mjs
 */

import {createRequire} from 'node:module'
import {mkdirSync, readFileSync, statSync, writeFileSync} from 'node:fs'
import {dirname, join, resolve} from 'node:path'
import {fileURLToPath} from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const ENTRY = join(ROOT, 'src/lib/ai/local-alt-text/localAltText.worker.ts')
const OUTPUT = join(ROOT, 'public/static/local-alt-text/worker.js')

const require = createRequire(import.meta.url)

let esbuild
try {
  esbuild = require('esbuild')
} catch {
  console.error(
    'esbuild is not installed. It normally comes with the Expo toolchain; run pnpm install.',
  )
  process.exit(1)
}

mkdirSync(dirname(OUTPUT), {recursive: true})

const result = await esbuild.build({
  entryPoints: [ENTRY],
  outfile: OUTPUT,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  legalComments: 'none',
  logLevel: 'warning',
  metafile: true,
})

const source = readFileSync(OUTPUT, 'utf8')
const size = statSync(OUTPUT).size

/*
 * Anything left as a bare specifier would be fetched from the page's server at
 * runtime and 404. The bundle is meant to be self-contained apart from the
 * wasm binaries, which transformers.js loads from its own CDN.
 */
const bareImports = [
  ...source.matchAll(
    /(?:^|[\n;])\s*import\s*(?:[^'"]*from\s*)?['"]([^'"./][^'"]*)['"]/g,
  ),
]
  .map(match => match[1])
  .filter(specifier => !specifier.startsWith('data:'))

if (bareImports.length > 0) {
  console.error(
    `worker.js still imports at runtime: ${[...new Set(bareImports)].join(', ')}`,
  )
  process.exit(1)
}

if (
  source.includes('require("sharp")') ||
  source.includes("require('sharp')")
) {
  console.error('worker.js pulled in the Node-only sharp dependency')
  process.exit(1)
}

writeFileSync(
  join(dirname(OUTPUT), 'README.md'),
  [
    '# local-alt-text worker',
    '',
    'Generated by `pnpm alt-text:build` from',
    '`src/lib/ai/local-alt-text/localAltText.worker.ts`.',
    '',
    'Do not edit `worker.js` by hand. The model weights and the wasm runtime are',
    'downloaded from the Hugging Face and jsDelivr CDNs at first use, so this file',
    'is the only thing served from our origin.',
    '',
  ].join('\n'),
)

const inputs = Object.keys(result.metafile.inputs).length
console.log(`worker.js: ${(size / 1024).toFixed(0)} KB from ${inputs} modules`)
